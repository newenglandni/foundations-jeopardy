function loadPreferredVoice() {
  if (!('speechSynthesis' in window)) return;
  const voices = window.speechSynthesis.getVoices();
  const englishVoices = voices.filter((voice) => voice.lang.toLowerCase().startsWith('en'));
  const premiumNaturalNames = /natural|neural|premium|enhanced|studio|google uk english male|microsoft guy|microsoft ryan|daniel|alex|reed|eddy|rocko/i;
  const naturalMaleNames = /daniel|alex|reed|eddy|rocko|david|fred|george|james|guy|ryan|male/i;
  const likelyFemaleNames = /samantha|victoria|karen|zira|susan|female/i;
  preferredVoice = englishVoices.find((voice) => premiumNaturalNames.test(voice.name) && naturalMaleNames.test(voice.name)) ||
    englishVoices.find((voice) => premiumNaturalNames.test(voice.name)) ||
    englishVoices.find((voice) => naturalMaleNames.test(voice.name)) ||
    englishVoices.find((voice) => !likelyFemaleNames.test(voice.name) && voice.lang.toLowerCase() === 'en-us') ||
    englishVoices.find((voice) => !likelyFemaleNames.test(voice.name)) ||
    englishVoices[0];
}

if ('speechSynthesis' in window) {
  loadPreferredVoice();
  window.speechSynthesis.addEventListener('voiceschanged', loadPreferredVoice);
}

function getAudioContext() {
  if (!audioContext) {
    audioContext = new (window.AudioContext || window.webkitAudioContext)();
  }
  if (audioContext.state === 'suspended') {
    audioContext.resume();
  }
  return audioContext;
}

function playTone(frequency, duration = 0.15, type = 'sine', volume = 0.06) {
  const context = getAudioContext();
  const oscillator = context.createOscillator();
  const gain = context.createGain();
  oscillator.type = type;
  oscillator.frequency.value = frequency;
  gain.gain.setValueAtTime(volume, context.currentTime);
  gain.gain.exponentialRampToValueAtTime(0.001, context.currentTime + duration);
  oscillator.connect(gain);
  gain.connect(context.destination);
  oscillator.start();
  oscillator.stop(context.currentTime + duration);
}

function speak(text, announce = false, onComplete = null) {
  if (!('speechSynthesis' in window)) {
    onComplete?.();
    return;
  }
  window.speechSynthesis.cancel();
  window.speechSynthesis.resume();
  const conversationalText = text
    .replace(/:\s*/g, ': ... ')
    .replace(/\.\s+/g, '. ... ');
  const utterance = new SpeechSynthesisUtterance(conversationalText);
  utterance.rate = announce ? 1.02 : 0.98;
  utterance.pitch = announce ? 1.08 : 1.04;
  utterance.volume = 1;
  if (preferredVoice) {
    utterance.voice = preferredVoice;
  }
  if (onComplete) {
    let completed = false;
    const completeOnce = () => {
      if (completed) return;
      completed = true;
      clearTimeout(fallbackTimer);
      onComplete();
    };
    const estimatedDuration = Math.max(1800, text.split(/\s+/).length * 230);
    const fallbackTimer = setTimeout(completeOnce, estimatedDuration);
    utterance.onend = completeOnce;
    utterance.onerror = completeOnce;
  }
  setTimeout(() => {
    try {
      window.speechSynthesis.resume();
      window.speechSynthesis.speak(utterance);
    } catch (error) {
      onComplete?.();
    }
  }, 60);
}

function stopTimer() {
  if (timerId) {
    clearInterval(timerId);
    timerId = null;
  }
}

function updateTimer() {
  timerEl.textContent = secondsRemaining;
  timerRow.classList.toggle('warning', secondsRemaining <= 10);
}

function startTimer() {
  stopTimer();
  secondsRemaining = ANSWER_TIME_SECONDS;
  updateTimer();
  timerId = setInterval(() => {
    secondsRemaining -= 1;
    updateTimer();
    if (secondsRemaining <= 0) {
      stopTimer();
      playTone(180, 0.35, 'square', 0.1);
      setTimeout(() => playTone(120, 0.45, 'square', 0.08), 180);
      speak("Time's up. The answer is now revealed.", true, () => showAnswer(true));
    }
  }, 1000);
}

function startMusic() {
  if (musicEnabled) return;
  musicEnabled = true;
  musicToggle.textContent = 'Music: On';
  musicToggle.setAttribute('aria-pressed', 'true');
  getAudioContext();
  // Original game-show-style motif: bright triads over a steady bass pulse.
  const melody = [392, 494, 587, 494, 440, 523, 659, 523];
  const bass = [98, 98, 110, 110];
  let beat = 0;
  const playMusicBeat = () => {
    if (!musicEnabled) return;
    playTone(bass[beat % bass.length], 0.42, 'triangle', 0.025);
    playTone(melody[beat % melody.length], 0.25, 'square', 0.018);
    if (beat % 4 === 0) {
      setTimeout(() => {
        if (musicEnabled) playTone(melody[(beat + 1) % melody.length] * 1.5, 0.2, 'sine', 0.012);
      }, 110);
    }
    beat += 1;
  };
  playMusicBeat();
  musicTimerId = setInterval(playMusicBeat, 420);
}

function stopMusic() {
  musicEnabled = false;
  musicToggle.textContent = 'Music: Off';
  musicToggle.setAttribute('aria-pressed', 'false');
  if (musicTimerId) {
    clearInterval(musicTimerId);
    musicTimerId = null;
  }
}

function renderLevelTabs() {
  levelTabs.innerHTML = '';
  levelOrder.forEach((levelKey) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = `level-tab ${state.activeLevel === levelKey ? 'active' : ''}`;
    btn.textContent = gameData[levelKey].name;
    btn.addEventListener('click', () => {
      state.activeLevel = levelKey;
      render();
    });
    levelTabs.appendChild(btn);
  });
}

function renderReviewPanel() {
  const totalClues = levelOrder.reduce((total, levelKey) =>
    total + gameData[levelKey].categories.reduce((levelTotal, category) => levelTotal + category.clues.length, 0), 0);
  const playedClues = Object.values(state.usedClues)
    .reduce((total, level) => total + Object.keys(level).length, 0);
  const finished = playedClues === totalClues;

  if (!finished || state.wrongAnswers.length === 0) {
    reviewPanel.classList.add('hidden');
    reviewPanel.innerHTML = '';
    return;
  }

  reviewPanel.classList.remove('hidden');
  reviewPanel.innerHTML = `
    <p class="eyebrow">Study review</p>
    <h2 id="review-title">Review Missed Questions</h2>
    <p class="review-intro">You finished the game. Use these missed questions to review the material and try again.</p>
    <div class="review-list">
      ${state.wrongAnswers.map((item, index) => `
        <article class="review-card">
          <div class="review-card-heading">
            <span>${item.levelName} • ${item.categoryName} • $${item.value}</span>
            <button type="button" class="read-review-btn" data-review-index="${index}">Read Aloud</button>
          </div>
          <p><strong>Question:</strong> ${item.question}</p>
          <p class="review-answer"><strong>Correct answer:</strong> ${item.answer}</p>
        </article>
      `).join('')}
    </div>
  `;
  reviewPanel.querySelectorAll('.read-review-btn').forEach((button) => {
    button.addEventListener('click', () => {
      const item = state.wrongAnswers[Number(button.dataset.reviewIndex)];
      speak(`Question: ${item.question}. The correct answer is: ${item.answer}`);
    });
  });
}

function renderBoard() {
  const level = gameData[state.activeLevel];
  const clueMap = state.usedClues[state.activeLevel] || {};

  boardEl.innerHTML = `
    <div class="level-header">
      <h2>${level.name}</h2>
      <span>${level.subtitle}</span>
    </div>
    <section class="board-grid">
      ${level.categories.map((category) => `
        <div class="category">
          <div class="category-header">${category.name}</div>
          ${category.clues.map((clue) => {
            const key = `${category.name}-${clue.value}`;
            const used = Boolean(clueMap[key]);
            return `
              <button
                type="button"
                class="clue ${used ? 'used' : ''}"
                data-category="${category.name}"
                data-value="${clue.value}"
                ${used ? 'disabled' : ''}
              >
                ${used ? '✓' : `$${clue.value}`}
              </button>
            `;
          }).join('')}
        </div>
      `).join('')}
    </section>
  `;

  boardEl.querySelectorAll('.clue').forEach((button) => {
    button.addEventListener('click', () => openModal(button.dataset.category, Number(button.dataset.value)));
  });
}

function openModal(categoryName, value) {
  const level = gameData[state.activeLevel];
  const category = level.categories.find((cat) => cat.name === categoryName);
  const clue = category.clues.find((item) => item.value === value);

  activeClue = { level: state.activeLevel, categoryName, value };
  modalTitle.textContent = categoryName;
  modalLevel.textContent = `${level.name} • $${value}`;
  modalBody.textContent = clue.question;
  answerBox.textContent = `Answer: ${clue.answer}`;
  answerBox.classList.add('hidden');
  answerControls.classList.add('hidden');
  modal.classList.remove('hidden');
  secondsRemaining = ANSWER_TIME_SECONDS;
  updateTimer();
  getAudioContext();
  speak(`For ${value} points: ${clue.question}`, false, () => {
    if (activeClue) {
      startTimer();
      try {
        startMusic();
      } catch (error) {
        // Audio is optional; the timer must continue if the browser blocks it.
      }
    }
  });
}

readQuestionBtn.addEventListener('click', () => {
  if (!activeClue) return;
  const level = gameData[activeClue.level];
  const category = level.categories.find((cat) => cat.name === activeClue.categoryName);
  const clue = category.clues.find((entry) => entry.value === activeClue.value);
  speak(`For ${activeClue.value} points: ${clue.question}`);
});

function markUsedAndClose() {
  if (!activeClue) return;
  const used = state.usedClues[activeClue.level] || {};
  used[`${activeClue.categoryName}-${activeClue.value}`] = true;
  state.usedClues[activeClue.level] = used;
  stopTimer();
  stopMusic();
  window.speechSynthesis?.cancel();
  activeClue = null;
  modal.classList.add('hidden');
  render();
}

function showAnswer(automatic = false) {
  if (!activeClue) return;
  stopTimer();
  stopMusic();
  answerBox.classList.remove('hidden');
  answerControls.classList.remove('hidden');
  const level = gameData[activeClue.level];
  const category = level.categories.find((cat) => cat.name === activeClue.categoryName);
  const clue = category.clues.find((entry) => entry.value === activeClue.value);
  if (automatic) {
    answerBox.textContent = `Answer: ${clue.answer}`;
  }
  speak(`The answer is: ${clue.answer}`);
}

function markCorrect() {
  if (!activeClue) return;
  const level = gameData[state.activeLevel];
  const category = level.categories.find((cat) => cat.name === activeClue.categoryName);
  const clue = category.clues.find((entry) => entry.value === activeClue.value);
  state.score += activeClue.value;
  scoreEl.textContent = state.score;
  playTone(660, 0.18, 'sine', 0.08);
  setTimeout(() => playTone(880, 0.25, 'sine', 0.08), 100);
  showAnswer();
  setTimeout(() => {
    markUsedAndClose();
  }, 5000);
}

function recordWrongAnswer(clue) {
  const level = gameData[activeClue.level];
  const key = `${activeClue.level}-${activeClue.categoryName}-${activeClue.value}`;
  if (state.wrongAnswers.some((item) => item.key === key)) return;
  state.wrongAnswers.push({
    key,
    levelName: level.name,
    categoryName: activeClue.categoryName,
    value: activeClue.value,
    question: clue.question,
    answer: clue.answer
  });
}

function markIncorrect() {
  if (!activeClue) return;
  const level = gameData[state.activeLevel];
  const category = level.categories.find((cat) => cat.name === activeClue.categoryName);
  const clue = category.clues.find((entry) => entry.value === activeClue.value);
  state.score = Math.max(0, state.score - activeClue.value);
  scoreEl.textContent = state.score;
  playTone(180, 0.35, 'sawtooth', 0.07);
  recordWrongAnswer(clue);
  showAnswer();
  setTimeout(() => {
    markUsedAndClose();
  }, 5000);
}

function resetGame() {
  stopTimer();
  window.speechSynthesis?.cancel();
  state.score = 0;
  state.usedClues = {};
  state.wrongAnswers = [];
  scoreEl.textContent = '0';
  render();
}

